# String to Integer
number = "10"
converted_number = int(number)

print("String:", number)
print("After conversion:", converted_number)
print("Type:", type(converted_number))

# Integer to Float
age = 21
converted_age = float(age)

print("\nInteger:", age)
print("After conversion:", converted_age)
print("Type:", type(converted_age))

# Integer to String
value = 100
converted_value = str(value)

print("\nInteger:", value)
print("After conversion:", converted_value)
print("Type:", type(converted_value))