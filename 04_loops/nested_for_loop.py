# Program 1 - Nested Loop
for i in range(1, 4):
    for j in range(1, 4):
        print(j, end=" ")
    print()

# Program 2 - Increasing Star Pattern
for i in range(1, 6):
    for j in range(1, i + 1):
        print("*", end=" ")
    print()

# Program 3 - Reverse Star Pattern
for i in range(5, 0, -1):
    for j in range(1, i + 1):
        print("*", end=" ")
    print()

# Program 4 - Number Pattern
for i in range(1, 6):
    for j in range(1, i + 1):
        print(j, end=" ")
    print()

# Program 5 — Number pattern
for i in range(1, 6):
    for j in range(1, i + 1):
        print(j, end=" ")
    print()

# Program 6 — Repeated number pattern
for i in range(1, 6):
    for j in range(1, i + 1):
        print(i, end=" ")
    print()

