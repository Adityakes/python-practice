numbers = (10, 20, 30, 40, 50, 60)

print("Tuple:", numbers)
print("First Three:", numbers[:3])
print("Middle Elements:", numbers[2:5])
print("Last Three:", numbers[-3:])
print("Reverse:", numbers[::-1])