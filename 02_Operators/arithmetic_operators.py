a = int(input("Enter Your 1st Number: "))
b = int(input("Enter Your 2nd Number: "))

print("a =", a)
print("b =", b)

print()

print("Addition       :", a + b)
print("Subtraction    :", a - b)
print("Multiplication :", a * b)
print("Division       :", a / b)
print("Floor Division :", a // b)
print("Modulus        :", a % b)
print("Exponent       :", a ** b)